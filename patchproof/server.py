def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class ApiError(Exception):
    def __init__(self, status: int, message: str, **extra: Any) -> None:
        super().__init__(message)
        self.status, self.message, self.extra = status, message, extra


# ---------------------------------------------------------------------------
# Jobs
# ---------------------------------------------------------------------------
class Job:
    def __init__(self, kind: str, run_id: str, stages: list[tuple[str, str]]) -> None:
        self.id = uuid.uuid4().hex[:12]
        self.kind, self.run_id = kind, run_id
        self.state = "queued"
        self.created_at = now_iso()
        self.started_at: str | None = None
        self.finished_at: str | None = None
        self.stages = [{"key": k, "label": label, "state": "pending", "detail": None,
                        "started_at": None, "finished_at": None} for k, label in stages]
        self.events: list[dict[str, Any]] = []
        self.log: list[str] = []
        self.error: str | None = None
        self.result: dict[str, Any] | None = None
        self.cancel_requested = False
        self.process: subprocess.Popen | None = None
        self.workdir_name: str | None = None
        self.lock = threading.Lock()

    def stage(self, key: str, state: str, detail: str | None = None) -> None:
        with self.lock:
            for s in self.stages:
                if s["key"] == key:
                    if state == "running" and not s["started_at"]:
                        s["started_at"] = now_iso()
                    if state in ("done", "failed", "skipped", "cancelled", "warn"):
                        s["finished_at"] = now_iso()
                    s["state"] = state
                    if detail is not None:
                        s["detail"] = detail

    def event(self, ev: dict[str, Any]) -> None:
        with self.lock:
            ev = {"t": round(time.time(), 3), **ev}
            self.events.append(ev)
            del self.events[:-400]

    def logline(self, line: str) -> None:
        with self.lock:
            self.log.append(line[:2000])
            del self.log[:-300]

    def snapshot(self) -> dict[str, Any]:
        with self.lock:
            return {"id": self.id, "kind": self.kind, "run_id": self.run_id, "state": self.state,
                    "created_at": self.created_at, "started_at": self.started_at, "finished_at": self.finished_at,
                    "stages": [dict(s) for s in self.stages], "events": list(self.events), "log_tail": self.log[-80:],
                    "error": self.error, "result": self.result, "cancel_requested": self.cancel_requested}


