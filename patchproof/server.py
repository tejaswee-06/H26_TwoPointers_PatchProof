def make_handler(app: App, port: int) -> type[BaseHTTPRequestHandler]:
    allowed_hosts = {f"{h}:{port}" for h in LOOPBACK} | LOOPBACK
    allowed_origins = {f"http://{h}:{p}" for h in ("127.0.0.1", "localhost", "[::1]") for p in (port, 5173, 4173)}

    class Handler(BaseHTTPRequestHandler):
        server_version = "PatchProof"
        protocol_version = "HTTP/1.1"

        def log_message(self, fmt: str, *args: Any) -> None:  # quieter console
            if os.environ.get("PATCHPROOF_HTTP_LOG"):
                super().log_message(fmt, *args)

        # -- helpers
        def _send(self, status: int, body: bytes, ctype: str, extra: dict[str, str] | None = None) -> None:
            self.send_response(status)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Referrer-Policy", "no-referrer")
            self.send_header("Cache-Control", "no-store" if ctype.startswith("application/json") else "no-cache")
            for k, v in (extra or {}).items():
                self.send_header(k, v)
            self.end_headers()
            if self.command != "HEAD":
                self.wfile.write(body)

        def _json(self, status: int, data: Any) -> None:
            self._send(status, json.dumps(data, ensure_ascii=False).encode("utf-8"), "application/json; charset=utf-8")

        def _read_raw(self) -> None:
            """Always consume the request body so keep-alive connections stay in sync."""
            try:
                n = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                n = 0
            if n > MAX_BODY:
                self.close_connection = True
                self._raw = None
                return
            self._raw = self.rfile.read(n) if n > 0 else b""

        def _body(self) -> dict[str, Any]:
            raw = getattr(self, "_raw", b"")
            if raw is None:
                raise ApiError(413, "Request body too large.")
            raw = raw or b"{}"
            try:
                data = json.loads(raw.decode("utf-8") or "{}")
            except (ValueError, UnicodeError):
                raise ApiError(400, "Request body must be JSON.")
            if not isinstance(data, dict):
                raise ApiError(400, "Request body must be a JSON object.")
            return data

        def _guard(self, mutating: bool) -> None:
            host = (self.headers.get("Host") or "").lower()
            if host not in allowed_hosts:
                raise ApiError(403, "Requests must target the local PatchProof server (loopback host).")
            origin = self.headers.get("Origin")
            if origin and origin.lower() not in allowed_origins:
                raise ApiError(403, "Cross-origin requests are not allowed.")
            if mutating and self.headers.get("X-PatchProof-Client") != "1":
                raise ApiError(403, "Missing X-PatchProof-Client header.")

        def do_HEAD(self) -> None:
            self.do_GET()

        def do_GET(self) -> None:
            self._dispatch("GET")

        def do_POST(self) -> None:
            self._dispatch("POST")

        def do_DELETE(self) -> None:
            self._dispatch("DELETE")

        def do_OPTIONS(self) -> None:  # never approve cross-origin pre-flights
            self._read_raw()
            self._json(403, {"error": "Cross-origin requests are not allowed."})

        def _dispatch(self, method: str) -> None:
            self._read_raw()
            url = urlparse(self.path)
            path = unquote(url.path)
            try:
                if not path.startswith("/api/"):
                    if method not in ("GET",):
                        raise ApiError(405, "Method not allowed.")
                    self._guard(False)
                    return self._static(path)
                self._guard(method != "GET")
                return self._api(method, path, parse_qs(url.query))
            except ApiError as exc:
                self._json(exc.status, {"error": exc.message, **exc.extra})
            except BrokenPipeError:
                pass
            except Exception as exc:  # noqa: BLE001
                traceback.print_exc()
                self._json(500, {"error": f"Internal error: {exc.__class__.__name__}: {exc}"})

        def _api(self, method: str, path: str, q: dict[str, list[str]]) -> None:
            parts = [p for p in path.split("/") if p][1:]  # drop 'api'
            if method == "GET" and parts == ["health"]:
                return self._json(200, health(app))
            if parts == ["runs"] and method == "GET":
                return self._json(200, {"runs": app.list_runs()})
            if parts == ["runs", "scan"] and method == "POST":
                return self._json(202, {"job": app.start_scan(self._body()).snapshot()})
            if parts == ["import"] and method == "POST":
                return self._json(201, app.import_files(self._body()))
            if parts == ["fs"] and method == "GET":
                return self._json(200, list_dir((q.get("path") or [None])[0]))
            if parts == ["jobs"] and method == "GET":
                return self._json(200, {"jobs": [j.snapshot() for j in app.jobs.values()
                                                 if not q.get("active") or j.state in ("queued", "running")]})
            if len(parts) == 2 and parts[0] == "jobs" and method == "GET":
                return self._json(200, {"job": app.get_job(parts[1]).snapshot()})
            if len(parts) == 3 and parts[0] == "jobs" and parts[2] == "cancel" and method == "POST":
                return self._json(200, {"job": app.cancel_job(parts[1])})
            if len(parts) >= 2 and parts[0] == "runs":
                rid = parts[1]
                rest = parts[2:]
                if not rest and method == "GET":
                    return self._json(200, app.run_detail(rid))
                if not rest and method == "DELETE":
                    app.delete_run(rid)
                    return self._json(200, {"deleted": rid})
                if rest == ["rescan"] and method == "POST":
                    meta = app.read_meta(rid)
                    if not meta.get("root_path"):
                        raise ApiError(409, "This run has no local repository folder to rescan.")
                    body = {"example": meta["example"]} if meta.get("example") else {"root": meta["root_path"], "exclude": meta.get("exclude") or []}
                    return self._json(202, {"job": app.start_scan(body).snapshot()})
                if rest == ["rebuild"] and method == "POST":
                    app.rebuild(rid)
                    return self._json(200, app.run_detail(rid))
                if rest == ["verify-template"] and method == "GET":
                    return self._json(200, app.verify_template(rid))
                if rest == ["verify"] and method == "POST":
                    return self._json(202, {"job": app.start_verify(rid, self._body()).snapshot()})
                if rest == ["ai"] and method == "POST":
                    val = app.store_ai(rid, self._body().get("artifact"))
                    return self._json(200, {"validation": val})
                if rest == ["ai"] and method == "DELETE":
                    app.remove_ai(rid)
                    return self._json(200, {"removed": True})
                if rest == ["ai", "run"] and method == "POST":
                    return self._json(202, {"job": app.start_ai(rid, self._body()).snapshot()})
                if rest == ["ai-input"] and method == "GET":
                    return self._json(200, app.evidence_bundle(rid))
                if len(rest) == 2 and rest[0] == "files" and method == "GET":
                    return self._file(rid, rest[1])
            raise ApiError(404, "Unknown endpoint.")

        def _file(self, rid: str, name: str) -> None:
            if name not in DOWNLOADABLE:
                raise ApiError(404, "Unknown artifact.")
            if name == "ai-input.json":
                body = json.dumps(app.evidence_bundle(rid), indent=2, ensure_ascii=False).encode("utf-8")
            else:
                p = app.run_dir(rid) / name
                if not p.is_file():
                    raise ApiError(404, f"{name} has not been produced for this run.")
                body = p.read_bytes()
            ctype = "text/markdown; charset=utf-8" if name.endswith(".md") else (
                "text/plain; charset=utf-8" if name.endswith(".log") else "application/json; charset=utf-8")
            self._send(200, body, ctype, {"Content-Disposition": f'attachment; filename="{name}"'})

        def _static(self, path: str) -> None:
            fd = app.frontend_dir
            if not fd or not (fd / "index.html").is_file():
                msg = ("<!doctype html><meta charset=utf-8><title>PatchProof</title><body style='font-family:system-ui;background:#07090d;color:#e8ebf0;padding:40px'>"
                       "<h1>PatchProof engine is running</h1><p>The dashboard has not been built yet. In another terminal run:</p>"
                       "<pre>cd frontend\nnpm install\nnpm run build</pre><p>then reload this page, or use <code>npm run dev</code> "
                       "and open http://127.0.0.1:5173.</p><p>API health: <a style='color:#4992ff' href='/api/health'>/api/health</a></p>")
                return self._send(200, msg.encode("utf-8"), "text/html; charset=utf-8")
            rel = path.lstrip("/") or "index.html"
            target = (fd / rel).resolve()
            if fd.resolve() not in target.parents and target != fd.resolve() / "index.html" or not target.is_file():
                target = fd / "index.html"  # SPA fallback (and traversal guard)
            ctype = mimetypes.guess_type(target.name)[0] or "application/octet-stream"
            if ctype.startswith("text/") or ctype in ("application/javascript",):
                ctype += "; charset=utf-8"
            extra = {"Cache-Control": "public, max-age=31536000, immutable"} if "/assets/" in path else {}
            self._send(200, target.read_bytes(), ctype, extra)

    return Handler


def health(app: App) -> dict[str, Any]:
    return {"ok": True, "engine_version": ENGINE_VERSION, "python": platform.python_version(),
            "platform": platform.system(), "workspace": app.workspace.name,
            "frontend_built": bool(app.frontend_dir and (app.frontend_dir / "index.html").is_file()),
            "ai_adapter": ai_bridge.adapter_status(),
            "examples": [{"id": k, "label": v["label"], "available": v["path"].is_dir()} for k, v in EXAMPLES.items()],
            "active_jobs": [j.snapshot() for j in app.jobs.values() if j.state in ("queued", "running")],
            "time": now_iso()}


def serve(host: str = "127.0.0.1", port: int = 8765, workspace: Path | None = None,
          frontend: Path | None = None, open_browser: bool = True) -> None:
    if host not in ("127.0.0.1", "localhost", "::1"):
        raise SystemExit("PatchProof binds to loopback only (127.0.0.1 / localhost / ::1).")
    ws = workspace or (PROJECT_ROOT / ".patchproof-workspace")
    fe = frontend or (PROJECT_ROOT / "frontend" / "dist")
    app = App(ws, fe)
    httpd = ThreadingHTTPServer((host, port), make_handler(app, port))
    httpd.daemon_threads = True
    url = f"http://{'127.0.0.1' if host != '::1' else '[::1]'}:{port}/"
    print(f"PatchProof {ENGINE_VERSION} — local dashboard at {url}")
    print(f"Workspace: {app.workspace}")
    print(f"Frontend: {'built' if (fe / 'index.html').is_file() else 'NOT BUILT (run: cd frontend && npm install && npm run build)'}")
    print(f"Gemma 4 adapter: {health(app)['ai_adapter']['state']}")
    print("Press Ctrl+C to stop.")
    if open_browser:
        threading.Timer(0.8, lambda: webbrowser.open(url)).start()
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping…")
        for j in list(app.jobs.values()):
            if j.process and j.process.poll() is None:
                _terminate_tree(j.process)
    finally:
        httpd.server_close()


