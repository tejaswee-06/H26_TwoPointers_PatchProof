# Application state
# ---------------------------------------------------------------------------
class App:
    def __init__(self, workspace: Path, frontend_dir: Path | None) -> None:
        self.workspace = workspace.resolve()
        self.runs_dir = self.workspace / "runs"
        self.runs_dir.mkdir(parents=True, exist_ok=True)
        self.frontend_dir = frontend_dir
        self.jobs: dict[str, Job] = {}
        self.jobs_lock = threading.Lock()
        self.run_locks: dict[str, threading.Lock] = {}
        self.verify_slot = threading.Semaphore(1)
        self.seed_bundled()

    # ---- runs -------------------------------------------------------------
    def run_lock(self, run_id: str) -> threading.Lock:
        with self.jobs_lock:
            return self.run_locks.setdefault(run_id, threading.Lock())

    def run_dir(self, run_id: str) -> Path:
        if not RUN_ID_RE.match(run_id or ""):
            raise ApiError(404, "Unknown run.")
        d = self.runs_dir / run_id
        if not (d / "run.json").is_file():
            raise ApiError(404, "Unknown run.")
        return d

    def read_meta(self, run_id: str) -> dict[str, Any]:
        d = self.run_dir(run_id)
        try:
            return json.loads((d / "run.json").read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise ApiError(500, f"Run metadata unreadable: {exc}")

    def write_meta(self, run_id: str, meta: dict[str, Any]) -> None:
        write_json(self.runs_dir / run_id / "run.json", meta)

    def new_run_id(self, name: str) -> str:
        slug = re.sub(r"[^a-z0-9]+", "-", (name or "repo").lower()).strip("-")[:32] or "repo"
        return f"{datetime.now().strftime('%Y%m%d-%H%M%S')}-{slug}-{uuid.uuid4().hex[:4]}"

    def seed_bundled(self) -> None:
        for rid, spec in BUNDLED.items():
            d = self.runs_dir / rid
            if (d / "run.json").is_file() or not spec["dir"].is_dir():
                continue
            d.mkdir(parents=True, exist_ok=True)
            for key in ("scan", "usage", "verification", "ai"):
                src = spec["dir"] / ARTIFACT_FILES[key]
                if src.is_file():
                    shutil.copy2(src, d / ARTIFACT_FILES[key])
            meta = {"id": rid, "created_at": now_iso(), "source": "bundled", "label": spec["label"], "note": spec["note"],
                    "root_name": spec["root_name"], "root_path": None, "state": "ready"}
            self.write_meta(rid, meta)
            self.rebuild(rid)

    def load_artifacts(self, run_id: str) -> dict[str, Any]:
        d = self.run_dir(run_id)
        out: dict[str, Any] = {}
        for key in ("scan", "usage", "verification", "ai", "diagnosis"):
            p = d / ARTIFACT_FILES[key]
            out[key] = load_json_artifact(p) if p.exists() else None
        return out

    def rebuild(self, run_id: str) -> dict[str, Any]:
        """Re-derive diagnosis and capsule from the run's stored artifacts."""
        with self.run_lock(run_id):
            d = self.run_dir(run_id)
            a = self.load_artifacts(run_id)
            diag = diagnose(a["scan"], a["usage"], a["verification"])
            write_json(d / ARTIFACT_FILES["diagnosis"], diag)
            capsule = build_capsule(a["scan"], a["usage"], a["ai"], a["verification"], diag)
            write_json(d / ARTIFACT_FILES["capsule"], capsule)
            (d / ARTIFACT_FILES["capsule_md"]).write_text(to_markdown(capsule), encoding="utf-8", newline="\n")
            meta = self.read_meta(run_id)
            meta.update(self._meta_summary(a, capsule))
            meta["capsule_built_at"] = now_iso()
            self.write_meta(run_id, meta)
            return capsule

    @staticmethod
    def _meta_summary(a: dict[str, Any], capsule: dict[str, Any]) -> dict[str, Any]:
        scan = a.get("scan") if isinstance(a.get("scan"), dict) else {}
        s = scan.get("summary") or {}
        usage = a.get("usage") if isinstance(a.get("usage"), dict) else {}
        return {"scan_status": scan.get("scan_status"),
                "summary": {"manifest_count": s.get("manifest_count"), "declaration_count": s.get("declaration_count"),
                            "finding_count": s.get("finding_count", len(scan.get("findings", []) or [])),
                            "error_count": s.get("error_count"),
                            "review_lead_count": len(usage.get("review_leads", []) or []),
                            "declared_packages": (usage.get("summary") or {}).get("declared_packages")},
                "verification_status": capsule.get("verification_status"),
                "overall_status": capsule.get("overall_status"),
                "ai_state": next((x["state"] for x in capsule.get("artifact_states", []) if x["artifact"] == "ai_analysis"), None)}

    def public_meta(self, meta: dict[str, Any]) -> dict[str, Any]:
        m = {k: v for k, v in meta.items() if k != "root_path"}
        m["can_verify"] = bool(meta.get("root_path")) and Path(meta["root_path"]).is_dir()
        m["can_rescan"] = m["can_verify"]
        m["deletable"] = meta.get("source") != "bundled"
        return m

    def list_runs(self) -> list[dict[str, Any]]:
        runs = []
        for d in sorted(self.runs_dir.iterdir(), reverse=True):
            if (d / "run.json").is_file():
                try:
                    runs.append(self.public_meta(json.loads((d / "run.json").read_text(encoding="utf-8"))))
                except (OSError, ValueError):
                    runs.append({"id": d.name, "state": "corrupt", "label": d.name, "deletable": True})
        runs.sort(key=lambda r: (r.get("source") == "bundled", r.get("created_at") or ""), reverse=True)
        runs.sort(key=lambda r: r.get("source") == "bundled")
        return runs

    def run_detail(self, run_id: str) -> dict[str, Any]:
        meta = self.read_meta(run_id)
        d = self.run_dir(run_id)
        a = self.load_artifacts(run_id)
        capsule = load_json_artifact(d / ARTIFACT_FILES["capsule"]) if (d / ARTIFACT_FILES["capsule"]).exists() else None
        capsule_summary = None
        if isinstance(capsule, dict):
            capsule_summary = {k: v for k, v in capsule.items() if k not in ("scan", "usage", "ai_analysis", "verification", "diagnosis")}
        md_path = d / ARTIFACT_FILES["capsule_md"]
        ids = ai_bridge.known_ids(a["scan"], a["usage"], a["diagnosis"])
        ai_validation = ai_bridge.validate_ai_artifact(a["ai"], ids) if isinstance(a["ai"], dict) and a["ai"].get("status") not in ("missing", "unreadable") else None
        cfg = None
        cfg_path = d / "verify-config.json"
        if cfg_path.is_file():
            try:
                cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
                cfg["target"] = "<TARGET>"
            except (OSError, ValueError):
                cfg = None
        files = sorted(p.name for p in d.iterdir() if p.name in DOWNLOADABLE)
        return {"run": self.public_meta(meta), "artifacts": a, "capsule": capsule_summary,
                "capsule_markdown": md_path.read_text(encoding="utf-8") if md_path.is_file() else None,
                "ai_validation": ai_validation, "verify_config": cfg, "files": files,
                "active_jobs": [j.snapshot() for j in self.jobs.values() if j.run_id == run_id and j.state in ("queued", "running")]}

    def delete_run(self, run_id: str) -> None:
        meta = self.read_meta(run_id)
        if meta.get("source") == "bundled":
            raise ApiError(403, "Bundled evidence runs cannot be deleted from the dashboard.")
        if any(j.run_id == run_id and j.state in ("queued", "running") for j in self.jobs.values()):
            raise ApiError(409, "Cancel the running job for this run first.")
        shutil.rmtree(self.runs_dir / run_id, ignore_errors=True)

    # ---- jobs -------------------------------------------------------------
    def add_job(self, job: Job, target: Callable[[Job], None]) -> Job:
        with self.jobs_lock:
            self.jobs[job.id] = job
            done = [j for j in self.jobs.values() if j.state not in ("queued", "running")]
            for old in done[:-50]:
                self.jobs.pop(old.id, None)

        def runner() -> None:
            job.state, job.started_at = "running", now_iso()
            try:
                target(job)
                if job.state == "running":
                    job.state = "cancelled" if job.cancel_requested else "succeeded"
            except Exception as exc:  # noqa: BLE001 - surface the failure in the UI
                job.state = "cancelled" if job.cancel_requested else "failed"
                job.error = job.error or f"{exc.__class__.__name__}: {exc}"
                job.logline(traceback.format_exc()[-3000:])
            finally:
                job.finished_at = now_iso()
        threading.Thread(target=runner, name=f"job-{job.id}", daemon=True).start()
        return job

    def get_job(self, job_id: str) -> Job:
        job = self.jobs.get(job_id)
        if not job:
            raise ApiError(404, "Unknown job.")
        return job

    def cancel_job(self, job_id: str) -> dict[str, Any]:
        job = self.get_job(job_id)
        if job.state not in ("queued", "running"):
            return job.snapshot()
        job.cancel_requested = True
        job.logline("Cancellation requested by user.")
        if job.process and job.process.poll() is None:
            _terminate_tree(job.process)
        return job.snapshot()

    # ---- scan ---------------------------------------------------------------
    def start_scan(self, body: dict[str, Any]) -> Job:
        example = body.get("example")
        if example:
            if example not in EXAMPLES:
                raise ApiError(422, "Unknown example.")
            root = EXAMPLES[example]["path"]
            label = EXAMPLES[example]["label"]
        else:
            raw = str(body.get("root") or "").strip().strip('"')
            if not raw:
                raise ApiError(422, "Enter the repository folder to scan.")
            root = Path(os.path.expanduser(raw))
            label = None
        if not root.is_absolute():
            raise ApiError(422, "Use an absolute folder path (for example C:\\projects\\LinkWatch).")
        if not root.is_dir():
            raise ApiError(422, "That folder does not exist or is not a directory.")
        root = root.resolve()
        if root == self.workspace or self.workspace in root.parents:
            raise ApiError(422, "The PatchProof workspace folder cannot be scanned.")
        exclude = tuple(str(x).strip() for x in body.get("exclude") or [] if str(x).strip())
        rid = self.new_run_id(example.replace("_", "-") if example else root.name)
        d = self.runs_dir / rid
        d.mkdir(parents=True)
        meta = {"id": rid, "created_at": now_iso(), "source": "scan", "label": label or root.name,
                "root_name": root.name, "root_path": str(root), "exclude": list(exclude), "state": "scanning",
                "example": example or None}
        self.write_meta(rid, meta)
        job = Job("scan", rid, [("validate", "Validate repository"), ("scan", "Scan manifests"),
                                ("usage", "Trace source imports"), ("diagnose", "Correlate evidence"),
                                ("capsule", "Build Exit Capsule")])

        def work(job: Job) -> None:
            ex = list(exclude)
            try:  # never scan our own workspace if it sits inside the repository
                ex.append(self.workspace.relative_to(root).as_posix())
            except ValueError:
                pass
            job.stage("validate", "done", f"{root.name}")
            steps: list[tuple[str, Callable[[], str]]] = []
            state: dict[str, Any] = {}

            def do_scan() -> str:
                state["scan"] = scan_repository(root, tuple(ex))
                write_json(d / ARTIFACT_FILES["scan"], state["scan"])
                s = state["scan"]["summary"]
                return f"{state['scan']['scan_status']} · {s['manifest_count']} manifest(s) · {s['finding_count']} finding(s) · {s['error_count']} error(s)"

            def do_usage() -> str:
                state["usage"] = trace_usage(root, tuple(ex), scan=state["scan"])
                write_json(d / ARTIFACT_FILES["usage"], state["usage"])
                u = state["usage"]["summary"]
                return f"{u['declared_packages']} package(s) · {len(state['usage'].get('review_leads', []))} review lead(s)"

            def do_diag() -> str:
                state["diag"] = diagnose(state["scan"], state["usage"], None)
                write_json(d / ARTIFACT_FILES["diagnosis"], state["diag"])
                return f"{state['diag']['summary']['candidate_count']} candidate(s) — runtime causes need verification output"

            def do_capsule() -> str:
                cap = self.rebuild(rid)
                return f"{cap['overall_status']} · verification {cap['verification_status']}"
            steps = [("scan", do_scan), ("usage", do_usage), ("diagnose", do_diag), ("capsule", do_capsule)]
            for key, fn in steps:
                if job.cancel_requested:
                    job.stage(key, "cancelled")
                    for k2, _ in steps[steps.index((key, fn)) + 1:]:
                        job.stage(k2, "cancelled")
                    shutil.rmtree(d, ignore_errors=True)
                    job.state = "cancelled"
                    job.result = {"run_deleted": True}
                    return
                job.stage(key, "running")
                try:
                    detail = fn()
                except Exception as exc:
                    job.stage(key, "failed", f"{exc.__class__.__name__}: {exc}")
                    m = self.read_meta(rid)
                    m.update({"state": "failed", "error": f"{key} stage failed: {exc.__class__.__name__}: {exc}"})
                    self.write_meta(rid, m)
                    job.error = m["error"]
                    raise
                job.stage(key, "warn" if key == "scan" and state["scan"]["scan_status"] != "completed" else "done", detail)
            m = self.read_meta(rid)
            m["state"] = "ready"
            self.write_meta(rid, m)
            job.result = {"run_id": rid}
        return self.add_job(job, work)

    # ---- verification -------------------------------------------------------
    def verify_template(self, run_id: str) -> dict[str, Any]:
        meta = self.read_meta(run_id)
        ex = meta.get("example")
        if ex and EXAMPLES.get(ex, {}).get("verify_config") and EXAMPLES[ex]["verify_config"].is_file():
            cfg = json.loads(EXAMPLES[ex]["verify_config"].read_text(encoding="utf-8"))
            cfg["target"] = "<TARGET>"
            return {"config": cfg, "source": "example verify-config.json shipped with the fixture"}
        a = self.load_artifacts(run_id)
        manifests = list((a.get("scan") or {}).get("manifests_scanned") or []) if isinstance(a.get("scan"), dict) else []
        install = ["{python}", "-m", "pip", "install"]
        reqs = [m for m in manifests if "/" not in m and m.startswith("requirements") and m.endswith(".txt")]
        for r in sorted(reqs, key=lambda x: (x != "requirements.txt", x)):
            install += ["-r", r]
        setup = []
        if len(install) > 4:
            setup.append(install)
        elif "pyproject.toml" in manifests or "setup.py" in manifests or "setup.cfg" in manifests:
            setup.append(["{python}", "-m", "pip", "install", "."])
        setup.append(["{python}", "-m", "pip", "install", "pytest"])
        cfg = {"target": "<TARGET>", "isolation": "venv", "timeout_seconds": 900,
               "baseline": {"setup": setup, "commands": [["{python}", "-m", "pip", "check"], ["{python}", "-m", "pytest", "-q"]]},
               "after": {"setup": setup, "commands": [["{python}", "-m", "pip", "check"], ["{python}", "-m", "pytest", "-q"]]},
               "change": {"pip_install": []}}
        return {"config": cfg, "source": "template derived from the scanned manifests — review every command before running"}

    def start_verify(self, run_id: str, body: dict[str, Any]) -> Job:
        meta = self.read_meta(run_id)
        if body.get("consent") is not True:
            raise ApiError(428, "Explicit consent is required: verification runs the configured repository commands, "
                                "which may execute arbitrary project code.")
        root = meta.get("root_path")
        if not root or not Path(root).is_dir():
            raise ApiError(409, "This run has no local repository folder (imported evidence). Scan the repository first, then verify that run.")
        if any(j.run_id == run_id and j.kind == "verify" and j.state in ("queued", "running") for j in self.jobs.values()):
            raise ApiError(409, "A verification is already running for this run.")
        cfg = body.get("config")
        if not isinstance(cfg, dict):
            raise ApiError(422, "'config' must be a JSON object.")
        cfg = {k: v for k, v in cfg.items() if not k.startswith("_")}
        cfg["target"] = root
        change = cfg.get("change")
        if isinstance(change, dict) and not change.get("pip_install") and not change.get("file_edits"):
            cfg.pop("change")  # an empty change block means "no change declared"
        if isinstance(cfg.get("after"), dict) and not cfg["after"].get("commands"):
            cfg.pop("after")
        try:
            validate_config(load_config(dict(cfg)))
        except ConfigError as exc:
            raise ApiError(422, f"Invalid verification configuration: {exc}")
        d = self.run_dir(run_id)
        cfg_path = d / "verify-config.json"
        write_json(cfg_path, cfg)
        out_tmp = d / "verification.partial.json"
        log_path = d / "verification.log"
        job = Job("verify", run_id, [("queue", "Wait for verification slot"), ("baseline", "Baseline run"),
                                    ("after", "After-change run"), ("record", "Record verification.json"),
                                    ("capsule", "Rebuild diagnosis + capsule")])
        if not cfg.get("after"):
            job.stage("after", "skipped", "No after-change commands configured")
        meta["consent"] = {"given_at": now_iso(), "statement": str(body.get("consent_statement") or "")[:500]}
        self.write_meta(run_id, meta)

        def work(job: Job) -> None:
            job.stage("queue", "running")
            while not self.verify_slot.acquire(timeout=0.5):
                if job.cancel_requested:
                    job.stage("queue", "cancelled")
                    job.state = "cancelled"
                    return
            try:
                job.stage("queue", "done", "Slot acquired")
                if job.cancel_requested:
                    job.state = "cancelled"
                    return
                self._run_verify_process(job, cfg_path, out_tmp, log_path)
                if job.cancel_requested:
                    for s in job.stages:
                        if s["state"] in ("pending", "running"):
                            job.stage(s["key"], "cancelled")
                    out_tmp.unlink(missing_ok=True)
                    job.state = "cancelled"
                    return
                job.stage("record", "running")
                data = load_json_artifact(out_tmp)
                if not isinstance(data, dict) or data.get("report_type") != "verification":
                    job.stage("record", "failed", "The verification process did not write a readable verification.json")
                    job.error = "Verification process ended without a readable result. See the log below."
                    job.state = "failed"
                    return
                os.replace(out_tmp, d / ARTIFACT_FILES["verification"])
                job.stage("record", "done", f"status {data.get('status')}")
                job.stage("capsule", "running")
                cap = self.rebuild(run_id)
                job.stage("capsule", "done", f"{cap['overall_status']} · {cap['verification_status']}")
                job.result = {"status": data.get("status"), "verified": cap["verification_assessment"]["verified"],
                              "status_reasons": data.get("status_reasons")}
            finally:
                self.verify_slot.release()
        return self.add_job(job, work)

    def _run_verify_process(self, job: Job, cfg_path: Path, out_tmp: Path, log_path: Path) -> None:
        out_tmp.unlink(missing_ok=True)
        env = dict(os.environ)
        env["PYTHONPATH"] = str(PROJECT_ROOT) + (os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
        env["PYTHONIOENCODING"] = "utf-8"
        argv = [sys.executable, "-m", "patchproof.verify", "--config", str(cfg_path), "--output", str(out_tmp), "--progress"]
        kwargs: dict[str, Any] = {}
        if os.name == "nt":
            kwargs["creationflags"] = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
        else:
            kwargs["start_new_session"] = True
        job.stage("baseline", "running", "Starting verification runner")
        proc = subprocess.Popen(argv, cwd=str(PROJECT_ROOT), env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, encoding="utf-8", errors="replace", **kwargs)
        job.process = proc
        with open(log_path, "w", encoding="utf-8") as log:
            def pump_stdout() -> None:
                assert proc.stdout
                for line in proc.stdout:
                    log.write(line)
                    job.logline(line.rstrip())
            t = threading.Thread(target=pump_stdout, daemon=True)
            t.start()
            assert proc.stderr
            for line in proc.stderr:
                if line.startswith("PATCHPROOF_PROGRESS "):
                    try:
                        ev = json.loads(line[len("PATCHPROOF_PROGRESS "):])
                    except ValueError:
                        continue
                    self._apply_progress(job, ev)
                    log.write(json.dumps(ev) + "\n")
                else:
                    log.write(line)
                    job.logline(line.rstrip())
            proc.wait()
            t.join(timeout=5)
        job.logline(f"Verification runner exited with code {proc.returncode}.")
        if job.cancel_requested and job.workdir_name and job.workdir_name.startswith("patchproof-verify-"):
            shutil.rmtree(Path(tempfile.gettempdir()) / job.workdir_name, ignore_errors=True)

    @staticmethod
    def _apply_progress(job: Job, ev: dict[str, Any]) -> None:
        name = ev.get("event")
        phase = ev.get("phase")
        job.event(ev)
        if name == "verification_started":
            job.workdir_name = ev.get("workdir_name")
            if "after" not in (ev.get("phases") or []):
                job.stage("after", "skipped", "No after-change commands configured")
        elif name == "phase_started" and phase in ("baseline", "after"):
            if phase == "after":
                job.stage("baseline", "done" if job.stages[1]["state"] == "running" else job.stages[1]["state"])
            job.stage(phase, "running", "Preparing disposable copy")
        elif name == "step" and phase in ("baseline", "after"):
            job.stage(phase, "running", ev.get("message"))
        elif name == "command_started" and phase in ("baseline", "after"):
            job.stage(phase, "running", f"{ev.get('kind')}: {ev.get('display')}")
        elif name == "phase_finished" and phase in ("baseline", "after"):
            job.stage(phase, "done" if ev.get("passed") else "warn",
                      "commands passed" if ev.get("passed") else "one or more commands failed (recorded)")
        elif name == "verification_finished":
            for key in ("baseline", "after"):
                st = next(s for s in job.stages if s["key"] == key)
                if st["state"] in ("running", "pending"):
                    job.stage(key, "failed" if ev.get("blockers") else "skipped",
                              "; ".join(ev.get("blockers") or [])[:300] or "not run")

    # ---- AI -----------------------------------------------------------------
    def store_ai(self, run_id: str, artifact: Any) -> dict[str, Any]:
        a = self.load_artifacts(run_id)
        ids = ai_bridge.known_ids(a["scan"], a["usage"], a["diagnosis"])
        val = ai_bridge.validate_ai_artifact(artifact, ids)
        if not val["valid"]:
            raise ApiError(422, "The AI analysis does not match the agreed schema; it was not stored.", validation=val)
        write_json(self.run_dir(run_id) / ARTIFACT_FILES["ai"], artifact)
        meta = self.read_meta(run_id)
        meta["ai_source"] = {"stored_at": now_iso(), "origin": "imported file"}
        self.write_meta(run_id, meta)
        self.rebuild(run_id)
        return val

    def remove_ai(self, run_id: str) -> None:
        (self.run_dir(run_id) / ARTIFACT_FILES["ai"]).unlink(missing_ok=True)
        self.rebuild(run_id)

    def evidence_bundle(self, run_id: str) -> dict[str, Any]:
        a = self.load_artifacts(run_id)
        return ai_bridge.build_evidence_bundle(a["scan"], a["usage"], a["verification"], a["diagnosis"])

    def start_ai(self, run_id: str, body: dict[str, Any]) -> Job:
        st = ai_bridge.adapter_status()
        if not st.get("available"):
            raise ApiError(409, st.get("reason") or "Gemma 4 adapter not connected.", adapter=st)
        self.run_dir(run_id)
        timeout = int(body.get("timeout_seconds") or 600)
        job = Job("ai", run_id, [("bundle", "Assemble evidence bundle"), ("model", "Local Gemma 4 inference"),
                                ("validate", "Validate AI schema"), ("capsule", "Rebuild capsule")])

        def work(job: Job) -> None:
            job.stage("bundle", "running")
            bundle = self.evidence_bundle(run_id)
            job.stage("bundle", "done", f"{len(bundle['findings'])} finding(s), {len(bundle['root_cause_candidates'])} candidate(s)")
            job.stage("model", "running", f"{st.get('model') or 'model id not reported'} via {st.get('runtime') or 'runtime not reported'}")
            out = ai_bridge.run_adapter(bundle, timeout)
            if job.cancel_requested:
                job.stage("model", "cancelled", "Result discarded after cancellation")
                job.state = "cancelled"
                return
            job.stage("model", "done")
            job.stage("validate", "running")
            try:
                val = self.store_ai(run_id, out)
            except ApiError as exc:
                job.stage("validate", "failed", exc.message)
                job.error = exc.message + " " + "; ".join(exc.extra.get("validation", {}).get("errors", []))
                job.state = "failed"
                return
            meta = self.read_meta(run_id)
            meta["ai_source"] = {"stored_at": now_iso(), "origin": "local adapter", "adapter": st.get("adapter_module")}
            self.write_meta(run_id, meta)
            job.stage("validate", "done", f"{len(val['warnings'])} warning(s)")
            job.stage("capsule", "done")
            job.result = {"warnings": val["warnings"]}
        return self.add_job(job, work)

    # ---- import -------------------------------------------------------------
    def import_files(self, body: dict[str, Any]) -> dict[str, Any]:
        files = body.get("files")
        if not isinstance(files, list) or not files:
            raise ApiError(422, "Select at least one JSON artifact.")
        found: dict[str, Any] = {}
        problems: list[dict[str, str]] = []
        for f in files:
            name = str((f or {}).get("name") or "file")[:120]
            try:
                data = json.loads(str((f or {}).get("content") or ""))
            except ValueError as exc:
                problems.append({"file": name, "error": f"Not valid JSON ({exc.msg} at line {exc.lineno})."})
                continue
            kind = classify_artifact(name, data)
            if kind is None:
                problems.append({"file": name, "error": "Could not identify this artifact type (scan, usage, verification, AI analysis or capsule)."})
                continue
            if kind == "capsule":
                for key, ck in (("scan", "scan"), ("usage", "usage"), ("verification", "verification"), ("ai", "ai_analysis")):
                    emb = data.get(ck)
                    if isinstance(emb, dict) and not (emb.get("status") in ("missing", "unreadable") and "schema_version" not in emb):
                        found.setdefault(key, emb)
                continue
            if kind in found:
                problems.append({"file": name, "error": f"A {kind} artifact was already supplied; this one was ignored."})
                continue
            found[kind] = data
        if not found:
            raise ApiError(422, "None of the selected files could be used.", problems=problems)
        ai_val = None
        if "ai" in found:
            ai_val = ai_bridge.validate_ai_artifact(found["ai"], ai_bridge.known_ids(found.get("scan"), found.get("usage")))
            if not ai_val["valid"]:
                problems.append({"file": "AI analysis", "error": "Schema errors: " + "; ".join(ai_val["errors"])})
                found.pop("ai")
        root_name = (found.get("scan") or {}).get("root") or (found.get("usage") or {}).get("root") or "imported"
        rid = self.new_run_id(f"import-{root_name}")
        d = self.runs_dir / rid
        d.mkdir(parents=True)
        for key, data in found.items():
            write_json(d / ARTIFACT_FILES[key], data)
        self.write_meta(rid, {"id": rid, "created_at": now_iso(), "source": "import",
                              "label": str(body.get("label") or f"Imported artifacts · {root_name}")[:120],
                              "root_name": root_name, "root_path": None, "state": "ready",
                              "imported_files": [str((f or {}).get("name"))[:120] for f in files]})
        self.rebuild(rid)
        return {"run_id": rid, "imported": sorted(found), "problems": problems}


def classify_artifact(name: str, data: Any) -> str | None:
    if not isinstance(data, dict):
        return None
    rt = data.get("report_type")
    mapping = {"scan": "scan", "patchproof_scan": "scan", "usage": "usage", "verification": "verification",
               "dependency_exit_capsule": "capsule"}
    if rt in mapping:
        return mapping[rt]
    n = name.lower()
    if "model" in data and ("options" in data or "analysis" in data):
        return "ai"
    if "ai-analysis" in n or "ai_analysis" in n:
        return "ai"
    if "capsule" in n and ("overall_status" in data or "verification_status" in data):
        return "capsule"
    if "usage" in n or "packages" in data and "review_leads" in data:
        return "usage"
    if "verification" in n or "verified" in data or "baseline" in data or "before" in data:
        return "verification"
    if "findings" in data or "declarations" in data:
        return "scan"
    return None


def _terminate_tree(proc: subprocess.Popen) -> None:
    try:
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True, timeout=20)
        else:
            os.killpg(proc.pid, signal.SIGTERM)

            def escalate() -> None:
                time.sleep(4)
                if proc.poll() is None:
                    try:
                        os.killpg(proc.pid, signal.SIGKILL)
                    except OSError:
                        pass
            threading.Thread(target=escalate, daemon=True).start()
    except (OSError, subprocess.SubprocessError):
        try:
            proc.kill()
        except OSError:
            pass


def list_dir(path: str | None) -> dict[str, Any]:
    if not path:
        home = Path.home()
        roots = []
        if os.name == "nt":
            import string
            roots = [f"{d}:\\" for d in string.ascii_uppercase if os.path.exists(f"{d}:\\")]
        return {"path": None, "parent": None, "roots": roots,
                "entries": [{"name": home.name or str(home), "path": str(home), "is_dir": True, "has_manifest": False}]
                + [{"name": r, "path": r, "is_dir": True, "has_manifest": False} for r in roots]}
    p = Path(os.path.expanduser(path))
    if not p.is_absolute() or not p.is_dir():
        raise ApiError(422, "Not an accessible folder.")
    entries = []
    try:
        for child in sorted(p.iterdir(), key=lambda c: c.name.lower()):
            if child.name.startswith(".") or not child.is_dir():
                continue
            try:
                has = any(_manifest_format(x.name) for x in child.iterdir() if x.is_file())
            except OSError:
                has = False
            entries.append({"name": child.name, "path": str(child), "is_dir": True, "has_manifest": has})
            if len(entries) >= 400:
                break
    except OSError as exc:
        raise ApiError(403, f"Cannot list folder: {exc.strerror or exc}")
    try:
        here_has = any(_manifest_format(x.name) for x in p.iterdir() if x.is_file())
    except OSError:
        here_has = False
    return {"path": str(p), "parent": str(p.parent) if p.parent != p else None, "entries": entries, "has_manifest": here_has}


