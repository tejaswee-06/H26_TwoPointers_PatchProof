"""PatchProof local API server (Person 3 integration layer).

Standard library only. Serves the built React dashboard and a small JSON API that
drives the Person 1 engine:

* scan + usage tracing + diagnosis + capsule run in-process (read-only; no repository code runs);
* verification runs ``python -m patchproof.verify`` as a cancellable subprocess and ONLY after the
  user explicitly consents to the exact configuration (repository commands may execute arbitrary code);
* AI analysis is accepted from Person 2's adapter or an imported ``ai-analysis.json`` and is always
  presented as a proposal.

Security model: binds to loopback only; rejects requests whose Host header is not loopback (DNS-rebinding
guard); state-changing requests must carry ``X-PatchProof-Client: 1`` (cross-site pages cannot add this
header without a CORS pre-flight, which this server never approves).

  python -m patchproof.server [--port 8765] [--workspace .patchproof-workspace] [--no-browser]
"""
